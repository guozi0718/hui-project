/* ---------- 请假时长（上学日）：三端同一口径 ----------
   当日应出勤时段按该班班次各时段的「上学时间–放学时间」取（分钟数），午休与时段之间的空档不计：
   一天四次打卡的班为 08:00–11:30、13:30–16:30；3年级-1班 另有晚自习 18:30–20:30；1年级-1班 为单段「全天」08:00–16:50。真实产品取该班班次配置。
   逐日取请假区间与各时段的重叠：当日每个时段都被完整覆盖记 1 个整天，否则重叠分钟累加为小时（保留 1 位小数）；周末跳过（演示未含节假日）。 */
const LVS_SEGS={'3年级-1班':[[480,690],[810,990],[1110,1230]],'1年级-1班':[[480,1010]]},LVS_SEGS_DEF=[[480,690],[810,990]];
function lvsSegs(cls){return LVS_SEGS[cls]||LVS_SEGS_DEF}
/* 当天最后一个时段的放学时间（分钟），全天单以此为结束时间 */
function lvsDayEnd(cls){const g=lvsSegs(cls);return g[g.length-1][1]}
/* s / e 为 Date 或「yyyy-MM-dd HH:mm」；返回 {days 整天数, mins 部分覆盖日的重叠分钟数, hasSchoolDay 区间内是否含上学日} */
function lvsSchoolMins(s,e,cls){
  const D=v=>typeof v==='string'?new Date(v.replace(' ','T')+':00'):new Date(v),a=D(s),b=D(e),g=lvsSegs(cls);
  const day=x=>new Date(x.getFullYear(),x.getMonth(),x.getDate()),a0=day(a),b0=day(b),am=a.getHours()*60+a.getMinutes(),bm=b.getHours()*60+b.getMinutes();
  let days=0,mins=0,has=false;
  for(let d=new Date(a0);d<=b0;d.setDate(d.getDate()+1)){
    const w=d.getDay();if(w===0||w===6)continue;has=true;
    const f0=+d===+a0?am:0,t0=+d===+b0?bm:1440;let full=true,m=0;
    g.forEach(([x,y])=>{const f=Math.max(f0,x),t=Math.min(t0,y);if(f>x||t<y)full=false;if(t>f)m+=t-f});
    if(full)days++;else mins+=m;
  }
  return {days:days,mins:mins,hasSchoolDay:has};
}
function lvsDurTxt(sd){const h=+(sd.mins/60).toFixed(1);return (!sd.days&&!h)?'0 小时':(sd.days?sd.days+' 天':'')+(sd.days&&h?' ':'')+(h?h+' 小时':'')}
/* 演示初值整理：结束于 16:00 的单按上述口径改到放学时间（从 08:00 起请的全天单取当天最后放学时间，其余取 16:30），并按区间现算时长 */
function lvsNorm(L){
  const hm=m=>String(Math.floor(m/60)).padStart(2,'0')+':'+String(m%60).padStart(2,'0');
  return L.map(r=>{
    if(r.e&&r.e.slice(11)==='16:00')r.e=r.e.slice(0,11)+(r.s.slice(11)==='08:00'?hm(lvsDayEnd(r.cls)):'16:30');
    r.dur=lvsDurTxt(lvsSchoolMins(r.s,r.st==='已销假'?r.cx:r.e,r.cls));
    if(r.st==='已销假')r.odur=lvsDurTxt(lvsSchoolMins(r.s,r.e,r.cls));
    if(r.st==='销假待确认')r.cxDur=lvsDurTxt(lvsSchoolMins(r.s,r.cx,r.cls));
    return r;
  });
}

