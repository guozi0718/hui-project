/* 代请人在该班的身份（学校端来源列「{老师}（{身份}代请假）」） */
function lvsRole(tid,cls){
  if(typeof dutyLoad!=='function')return '';
  const c=(dutyLoad().classes||[]).find(x=>x.c===cls);if(!c)return '';
  if(c.head===tid||(c.dep||[]).includes(tid))return '班主任';
  if((c.sub||[]).includes(tid))return '任课老师';
  return '';
}
