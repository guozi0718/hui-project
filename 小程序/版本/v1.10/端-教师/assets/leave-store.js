function lvsLoad(){
  let L=null;
  try{L=JSON.parse(localStorage.getItem(LVS_KEY)||'null')}catch(e){L=null}
  if(!Array.isArray(L))L=lvsSeed();
  return L;
}
function lvsSave(L){try{localStorage.setItem(LVS_KEY,JSON.stringify(L))}catch(e){}}
function lvsReset(){try{localStorage.removeItem(LVS_KEY)}catch(e){};lvsTeachers=null}
const lvsGet=id=>lvsLoad().find(r=>r.id===id);
/* 读-改-写：每次以存储中的最新数据为准，fn 返回 false 时不写入 */
function lvsUpdate(id,fn){
  const L=lvsLoad(),r=L.find(x=>x.id===id);if(!r)return null;
  if(fn(r,L)===false)return r;
  lvsSave(L);return r;
}
function lvsAdd(r){const L=lvsLoad();L.push(r);lvsSave(L);return r}
/* 演示「现在」：固定 7月6日 17:05；已有节点晚于此刻时顺延 1 分钟，保证新节点排在最后 */
function lvsNow(L){
  let max=lvsMs(LVS_NOW);
  (L||lvsLoad()).forEach(r=>r.tl.forEach(x=>{if(x.at){const t=lvsMs(x.at);if(t>=max)max=t+60000}}));
  return lvsFmt(max);
}
