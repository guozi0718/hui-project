function lvsOnChange(cb){
  window.addEventListener('storage',e=>{
    if(typeof STORE!=='undefined'&&e.key===STORE)lvsTeachers=null;
    if(e.key===LVS_KEY||e.key===null||(typeof STORE!=='undefined'&&e.key===STORE))cb();
  });
}
